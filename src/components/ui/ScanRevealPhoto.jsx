const ASCII_ART = ASCII_ART_LINES.join("\n");

export default function ScanRevealPhoto({ src, alt }) {
  const ref = useRef(null);
  // The ref sits on a plain wrapper, not the clipped/animated elements
  // themselves, so IntersectionObserver measures real, untransformed geometry.
  const isInView = useInView(ref, { once: false, amount: 0.5 });

  return (
    <div
      ref={ref}
      className="relative mx-auto max-w-xs aspect-[4/5] rounded-2xl overflow-hidden border border-emerald/30 bg-black shadow-[0_0_30px_-5px_rgba(16,185,129,0.45)]"
    >
      {/* Real photo — revealed as the scan line wipes the ASCII layer away */}
      <img
        src={src}
        alt={alt}
        className="absolute inset-0 h-full w-full object-cover"
        onError={(e) => {
          e.currentTarget.style.display = "none";
        }}
      />

      {/* ASCII layer — stays put while the laser scans, then wipes away to reveal the photo */}
      <motion.pre
        initial={false}
        animate={{ clipPath: isInView ? "inset(100% 0 0 0)" : "inset(0% 0 0 0)" }}
        transition={
          isInView
            ? { duration: 0.8, delay: SCAN_DURATION, ease: [0.65, 0, 0.35, 1] }
            : { duration: 0.3 }
        }
        className="absolute inset-0 m-0 flex items-center justify-center bg-black font-mono text-[6.5px] sm:text-[7.5px] leading-[1.15] text-emerald whitespace-pre"
        style={{ textShadow: "0 0 6px rgba(16,185,129,0.85), 0 0 14px rgba(16,185,129,0.45)" }}
      >
        {ASCII_ART}
      </motion.pre>

      {/* Glowing scan line — rests at the top; once triggered, sweeps up/down like
          a scanner for SCAN_DURATION seconds, then fades out as the photo reveals */}
      <motion.div
        initial={false}
        animate={
          isInView
            ? { top: ["0%", "100%", "0%", "100%", "0%"], opacity: [1, 1, 1, 1, 0] }
            : { top: "0%", opacity: 1 }
        }
        transition={
          isInView
            ? { duration: SCAN_DURATION, times: [0, 0.25, 0.5, 0.75, 1], ease: "easeInOut" }
            : { duration: 0.3 }
        }
        className="absolute left-0 right-0 h-[3px] bg-emerald shadow-[0_0_14px_3px_rgba(16,185,129,0.9)]"
      />
    </div>
  );
}
